/**
 * Brand asset pipeline.
 *
 * Reads the supplied logo (`brand/fds-logo.source.svg`, a bitmap trace with a
 * white canvas, one dark mark, two white counter shapes and a terracotta
 * square) and emits everything the site needs from it:
 *
 *   src/components/layout/logo-paths.ts   path data for the React <LogoMark>
 *   src/app/icon.svg                      favicon (SVG), white mark on espresso
 *   src/app/icon.png                      favicon (32 px, for browsers without SVG favicons)
 *   src/app/apple-icon.png                180 px home-screen icon
 *   public/images/og-default.<hash>.png   1200×630 social-share image
 *   src/generated/brand.ts                the hashed OG path for metadata
 *
 * The counters sit inside the mark outline, so mark + counters become one
 * compound path with fill-rule evenodd: a single `currentColor` path that
 * works on light and dark surfaces alike.
 *
 *   npm run brand
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const SOURCE = path.join(ROOT, "brand", "fds-logo.source.svg");

/* Palette (mirrors src/styles/globals.css). */
const PAPER = "#faf8f5";
const ESPRESSO = "#2a211c";
const INK = "#1f1a17";
const MUTED = "#5c5049";
const ACCENT = "#d57b47";

/* Tight box around mark + square, with ~6% padding. */
const VIEWBOX = { x: 42, y: 91, w: 358, h: 222 };
/* Square framing for icons: same width, vertically centred. */
const ICON_BOX = { x: 42, y: 91 - (358 - 222) / 2, w: 358, h: 358 };

type SourcePath = { d: string; fill: string; tx: number; ty: number };

function fail(message: string): never {
  console.error(`\n✖ ${message}\n`);
  process.exit(1);
}

function parseSource(svg: string): SourcePath[] {
  const paths: SourcePath[] = [];
  const re = /<path\s+([^>]*?)\/>/g;
  for (const match of svg.matchAll(re)) {
    const attrs = match[1] ?? "";
    const d = /d="([^"]+)"/.exec(attrs)?.[1];
    const fill = /fill="([^"]+)"/.exec(attrs)?.[1] ?? "";
    const translate = /translate\(([-\d.]+),([-\d.]+)\)/.exec(attrs);
    if (!d) continue;
    paths.push({
      d,
      fill: fill.toUpperCase(),
      tx: translate ? Number(translate[1]) : 0,
      ty: translate ? Number(translate[2]) : 0,
    });
  }
  return paths;
}

/** Bakes a translate() into absolute M/L/C path data. */
function translatePath(d: string, tx: number, ty: number): string {
  const tokens = d.match(/[MLCZmlcz]|-?\d*\.?\d+(?:e-?\d+)?/g) ?? [];
  const out: string[] = [];
  let command = "";
  let index = 0;
  for (const token of tokens) {
    if (/^[MLCZmlcz]$/.test(token)) {
      if (/[mlc]/.test(token)) fail(`relative path command "${token}" is not supported`);
      command = token;
      index = 0;
      out.push(token);
      continue;
    }
    if (command === "Z") continue;
    const value = Number(token);
    const shifted = index % 2 === 0 ? value + tx : value + ty;
    out.push(String(Math.round(shifted * 100) / 100));
    index += 1;
  }
  return out.join(" ").replace(/\s+([MLCZ])/g, " $1");
}

function sha1(buffer: Buffer): string {
  return createHash("sha1").update(buffer).digest("hex").slice(0, 8);
}

async function renderPng(svg: string, width: number, height: number): Promise<Buffer> {
  const { data, info } = await sharp(Buffer.from(svg))
    .png({ compressionLevel: 9, palette: false })
    .toBuffer({ resolveWithObject: true });
  if (info.width !== width || info.height !== height) {
    fail(`expected ${width}×${height}, rendered ${info.width}×${info.height}`);
  }
  return data;
}

async function main(): Promise<void> {
  if (!fs.existsSync(SOURCE)) fail(`missing ${path.relative(ROOT, SOURCE)}`);
  const parsed = parseSource(fs.readFileSync(SOURCE, "utf8"));

  const mark = parsed.find((p) => p.fill === "#272727");
  const counters = parsed.filter((p) => p.fill === "#FCFCFC");
  const square = parsed.find((p) => p.fill === "#D57B47");
  if (!mark || counters.length !== 2 || !square) {
    fail("source SVG does not have the expected mark / two counters / accent square");
  }

  const markD = [mark, ...counters].map((p) => translatePath(p.d, p.tx, p.ty)).join(" ");
  const squareD = translatePath(square.d, square.tx, square.ty);
  const viewBox = `${VIEWBOX.x} ${VIEWBOX.y} ${VIEWBOX.w} ${VIEWBOX.h}`;

  /* 1. Path data for the React component. */
  fs.writeFileSync(
    path.join(ROOT, "src", "components", "layout", "logo-paths.ts"),
    `// AUTO-GENERATED by scripts/build-brand.ts from brand/fds-logo.source.svg. Do not edit.
export const LOGO_VIEWBOX = "${viewBox}";
/** Mark + counters as one compound path; render with fillRule="evenodd". */
export const LOGO_MARK_D =
  "${markD}";
export const LOGO_SQUARE_D = "${squareD}";
`,
  );

  /* 2. Favicons: white mark on the dark espresso surface. */
  const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${ICON_BOX.x} ${ICON_BOX.y} ${ICON_BOX.w} ${ICON_BOX.h}"><rect x="${ICON_BOX.x}" y="${ICON_BOX.y}" width="${ICON_BOX.w}" height="${ICON_BOX.h}" rx="64" fill="${ESPRESSO}"/><path fill="${PAPER}" fill-rule="evenodd" d="${markD}"/><path fill="${ACCENT}" d="${squareD}"/></svg>`;
  fs.writeFileSync(path.join(ROOT, "src", "app", "icon.svg"), `${iconSvg}\n`);

  const icon32 = `<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32"><rect width="32" height="32" rx="6" fill="${ESPRESSO}"/><svg x="2" y="2" width="28" height="28" viewBox="${ICON_BOX.x} ${ICON_BOX.y} ${ICON_BOX.w} ${ICON_BOX.h}"><path fill="${PAPER}" fill-rule="evenodd" d="${markD}"/><path fill="${ACCENT}" d="${squareD}"/></svg></svg>`;
  fs.writeFileSync(path.join(ROOT, "src", "app", "icon.png"), await renderPng(icon32, 32, 32));

  const apple = `<svg xmlns="http://www.w3.org/2000/svg" width="180" height="180" viewBox="0 0 180 180"><rect width="180" height="180" fill="${ESPRESSO}"/><svg x="20" y="46" width="140" height="87" viewBox="${viewBox}"><path fill="${PAPER}" fill-rule="evenodd" d="${markD}"/><path fill="${ACCENT}" d="${squareD}"/></svg></svg>`;
  fs.writeFileSync(
    path.join(ROOT, "src", "app", "apple-icon.png"),
    await renderPng(apple, 180, 180),
  );

  /* 3. Social-share image. Text uses a system sans: librsvg cannot load the site's woff2. */
  const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="${PAPER}"/>
  <svg x="100" y="120" width="322" height="200" viewBox="${viewBox}"><path fill="${INK}" fill-rule="evenodd" d="${markD}"/><path fill="${ACCENT}" d="${squareD}"/></svg>
  <text x="100" y="430" font-family="Segoe UI, Arial, Helvetica, sans-serif" font-size="64" font-weight="700" fill="${INK}">Fast Digital Solutions</text>
  <text x="100" y="492" font-family="Segoe UI, Arial, Helvetica, sans-serif" font-size="30" fill="${MUTED}">Cloud, AI, software engineering and quality for growing organizations</text>
  <rect x="0" y="618" width="1200" height="12" fill="${ACCENT}"/>
</svg>`;
  const ogPng = await renderPng(og, 1200, 630);
  const ogName = `og-default.${sha1(ogPng)}.png`;
  const imagesDir = path.join(ROOT, "public", "images");
  fs.mkdirSync(imagesDir, { recursive: true });
  for (const file of fs.readdirSync(imagesDir)) {
    if (/^og-default\.[0-9a-f]{8}\.png$/.test(file) && file !== ogName) {
      fs.unlinkSync(path.join(imagesDir, file));
    }
  }
  fs.writeFileSync(path.join(imagesDir, ogName), ogPng);
  fs.mkdirSync(path.join(ROOT, "src", "generated"), { recursive: true });
  fs.writeFileSync(
    path.join(ROOT, "src", "generated", "brand.ts"),
    `// AUTO-GENERATED by scripts/build-brand.ts. Do not edit.
export const OG_IMAGE = { url: "/images/${ogName}", width: 1200, height: 630 } as const;
`,
  );

  console.log(
    `Brand assets written: logo-paths.ts, icon.svg, icon.png, apple-icon.png, ${ogName} (${Math.round(ogPng.byteLength / 1024)} KB)`,
  );
}

main().catch((error) => fail(error instanceof Error ? error.message : String(error)));
